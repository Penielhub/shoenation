"""Export the API docs so people can browse them without running the backend.

Run from backend/ after changing any endpoint:  python -m app.export_docs

Writes, at the repo root:
  docs/api/openapi.json  the API description (what Swagger UI reads)
  docs/api/index.html    a standalone Swagger UI page with the description built in
"""
import json
import os
from pathlib import Path

# the docs only describe the API, so no real database or secret is needed to build them.
# setdefault keeps a real .env value if one is loaded; nothing here connects or signs anything.
os.environ.setdefault("DATABASE_URL", "postgresql+psycopg2://docs:docs@localhost/docs")
os.environ.setdefault("SECRET_KEY", "only-used-to-build-the-docs")

from .main import app  # noqa: E402  (must come after the defaults above)

OUT = Path(__file__).resolve().parents[2] / "docs" / "api"

# "Try it out" sends requests here, so it works for anyone running the backend locally
SERVERS = [{"url": "http://localhost:8000", "description": "Your local backend (uvicorn app.main:app --reload)"}]

PAGE = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Shoenation API docs</title>
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui.css">
  <style>body {{ margin: 0; }}</style>
</head>
<body>
  <div id="swagger-ui"></div>
  <script src="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui-bundle.js"></script>
  <script>
    // generated by backend/app/export_docs.py, don't edit by hand
    window.ui = SwaggerUIBundle({{ spec: {spec}, dom_id: "#swagger-ui", deepLinking: true }});
  </script>
</body>
</html>
"""


def main():
    spec = app.openapi()
    spec = {**spec, "servers": SERVERS}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "openapi.json").write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    # "</" inside a <script> could end the tag early, so it's escaped in the embedded copy
    embedded = json.dumps(spec).replace("</", "<\\/")
    (OUT / "index.html").write_text(PAGE.format(spec=embedded), encoding="utf-8")
    paths = sum(len(ops) for ops in spec["paths"].values())
    print(f"Wrote {OUT / 'openapi.json'} and index.html ({paths} endpoints)")


if __name__ == "__main__":
    main()
